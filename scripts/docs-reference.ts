#!/usr/bin/env bun
/**
 * Prints the CLI reference of the docs site (actovia.yancey.app/docs/cli/reference)
 * as MDX, walked from the same command definitions the CLI parses with, so
 * the page cannot drift from the commands. The homepage repo keeps the output
 * in `content/docs/cli/reference.mdx`:
 *
 *   bun run docs:reference > ../homepage/content/docs/cli/reference.mdx
 */
import type { Command } from 'commander'

import { buildProgram } from '../src/cli'

function usage(cmd: Command, path: string[]): string {
  const args = cmd.registeredArguments.map(a => (a.required ? `<${a.name()}>` : `[${a.name()}]`))
  const options = cmd.options.some(o => !o.flags.includes('--version')) ? ['[options]'] : []
  return [...path, cmd.name(), ...options, ...args].join(' ')
}

// MDX reads `<` and `{` outside code as JSX.
const prose = (text: string) => text.replace(/[<>{}]/gu, c => `\\${c}`)

function section(cmd: Command, path: string[], out: string[]): void {
  const name = [...path, cmd.name()].join(' ')
  out.push(`## ${name}`, '', prose(cmd.description()), '', '```bash', usage(cmd, path), '```', '')
  const options = cmd.options.filter(o => !o.flags.includes('--version'))
  if (options.length > 0) {
    out.push('| Option | Description |', '| --- | --- |')
    for (const o of options) out.push(`| \`${o.flags}\` | ${prose(o.description)} |`)
    out.push('')
  }
  for (const sub of cmd.commands) section(sub, [...path, cmd.name()], out)
}

const program = buildProgram()
const out = [
  '---',
  'title: Command reference',
  'description: Every actovia command and option.',
  '---',
  '',
  '{/* Generated by `bun run docs:reference` in actovia-ai/cli — do not edit by hand. */}',
  '',
  'Every command takes `-h, --help`; `actovia -V` prints the version.',
  ''
]
for (const cmd of program.commands) section(cmd, [program.name()], out)
process.stdout.write(out.join('\n'))
